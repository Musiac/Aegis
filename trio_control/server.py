"""Host-side control plane for the ephemeral sandbox trio (aegis-sandbox, aegis-sandbox-proxy, aegis-sandbox-web).

Runs as a PLAIN HOST PROCESS (not a container) -- deliberately, so aegis-code (itself a container, with no
docker.sock today) never gains general Docker control. aegis-code reaches this over host.docker.internal
(Docker Desktop's bridge-to-host DNS name), and this process is the only thing with real `docker` CLI access.
It exposes exactly 2 real actions, start/stop the trio -- not a generic Docker API, so even full compromise of
aegis-code (prompt injection, whatever) cannot pivot into controlling any OTHER container on this host.

Binds 0.0.0.0 but enforces an IP allowlist in code (loopback + the default Docker bridge subnet only --
see _ALLOWED_CLIENT_NETS below) and requires a bearer token (TRIO_CONTROL_TOKEN in .env, generated by
install.sh the same way REDTEAM_TOKEN/PENTESTLIVE_TOKEN are) as a second, independent layer -- same
defense-in-depth pattern pentestlive_server.py already uses for its own SSRF check.
"""
import ipaddress
import json
import os
import subprocess
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

TOKEN = os.environ["TRIO_CONTROL_TOKEN"]
REPO_ROOT = os.environ["AEGIS_REPO_ROOT"]
PORT = int(os.environ.get("TRIO_CONTROL_PORT", "7929"))
# How long the trio may sit idle (no /start or /touch call) before the reaper tears it down. Deliberately not
# tied to export_project succeeding -- a real task often exports, then still needs the sandbox again right
# after (append_doc_to_export attaching a report into the same zip, or a further fix/re-scan round), so
# tearing down on export alone would recreate the trio seconds after destroying it. Idle time is the one
# signal that doesn't need to guess where a "task" actually ends.
IDLE_TIMEOUT_S = float(os.environ.get("TRIO_IDLE_TIMEOUT_S", "300"))

_lock = threading.Lock()
_last_touch = 0.0


TRIO_NAMES = ("aegis-sandbox", "aegis-sandbox-proxy", "aegis-sandbox-web")


def _run(argv: list[str]) -> tuple[int, str]:
    # argv list, no shell: nothing here is ever parsed by a shell, so no string can be injected into a command.
    p = subprocess.run(argv, cwd=REPO_ROOT, capture_output=True, text=True, timeout=120)
    return p.returncode, (p.stdout + p.stderr)


def _trio_running() -> bool:
    rc, out = _run(["docker", "ps", "--format", "{{.Names}}"])
    return rc == 0 and set(TRIO_NAMES) <= set(out.split())


def touch() -> None:
    global _last_touch
    _last_touch = time.monotonic()


def start_trio() -> dict:
    touch()
    with _lock:
        if _trio_running():
            return {"ok": True, "already_running": True}
        rc, out = _run(["bash", "trio_control/start_trio.sh"])
        if rc != 0:
            return {"ok": False, "error": out[-4000:]}
        return {"ok": True, "already_running": False}


def stop_trio() -> dict:
    with _lock:
        rc, out = _run(["docker", "rm", "-f", *TRIO_NAMES])
        return {"ok": rc == 0, "output": out[-2000:]}


def status() -> dict:
    return {"running": _trio_running()}


def _reaper() -> None:
    while True:
        time.sleep(30)
        with _lock:
            idle_for = time.monotonic() - _last_touch
            if idle_for >= IDLE_TIMEOUT_S and _trio_running():
                rc, out = _run(["docker", "rm", "-f", *TRIO_NAMES])
                print(f"[trio_control] idle {idle_for:.0f}s >= {IDLE_TIMEOUT_S:.0f}s, reaped trio (rc={rc})", flush=True)


# Which client IPs may even attempt a request, checked BEFORE the bearer token (2026-10-31, real incident
# found deploying cyberJiina's identical trio_control to the DGX): on native Linux Docker (the DGX, EC2 --
# NOT Docker Desktop), `host.docker.internal` does not resolve at all without
# `--add-host=host.docker.internal:host-gateway` on the calling container, and even once that's added it
# resolves to the docker0 bridge gateway IP (172.17.0.1 by default), NOT 127.0.0.1 -- so a server bound to
# 127.0.0.1 only is correctly unreachable from inside a container on that platform. The naive fix (bind
# 0.0.0.0) would also make this reachable from EVERY other interface on the host, including a Tailscale/LAN
# interface other services use to reach this host -- a real, unnecessary widening of this process's own
# stated design ("never reachable from outside this host"). Binding 0.0.0.0 but enforcing this allowlist in
# code gets the container reachability Linux needs without that widening: only loopback and the default
# Docker bridge subnet are ever allowed in, regardless of which interface actually received the connection.
_ALLOWED_CLIENT_NETS = [ipaddress.ip_network("127.0.0.0/8"), ipaddress.ip_network("172.16.0.0/12")]


class Handler(BaseHTTPRequestHandler):
    def _reply(self, code: int, body: dict):
        data = json.dumps(body).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def _client_allowed(self) -> bool:
        try:
            ip = ipaddress.ip_address(self.client_address[0])
        except ValueError:
            return False
        return any(ip in net for net in _ALLOWED_CLIENT_NETS)

    def _authed(self) -> bool:
        return self.headers.get("Authorization") == f"Bearer {TOKEN}"

    def do_POST(self):
        if not self._client_allowed():
            self._reply(403, {"error": "client not allowed"})
            return
        if not self._authed():
            self._reply(401, {"error": "bad token"})
            return
        if self.path == "/start":
            self._reply(200, start_trio())
        elif self.path == "/stop":
            self._reply(200, stop_trio())
        elif self.path == "/touch":
            touch()
            self._reply(200, {"ok": True})
        else:
            self._reply(404, {"error": "no such endpoint"})

    def do_GET(self):
        if not self._client_allowed():
            self._reply(403, {"error": "client not allowed"})
            return
        if self.path == "/status":
            self._reply(200, status())
        else:
            self._reply(404, {"error": "no such endpoint"})

    def log_message(self, fmt, *args):
        pass


if __name__ == "__main__":
    threading.Thread(target=_reaper, daemon=True).start()
    # 0.0.0.0, not 127.0.0.1-only: native Linux Docker containers reach the host via the docker0 bridge
    # gateway IP, not loopback (see _ALLOWED_CLIENT_NETS's own comment above) -- the IP allowlist check on
    # every request is what keeps this host-local-only, not the bind address.
    ThreadingHTTPServer(("0.0.0.0", PORT), Handler).serve_forever()  # nosec B104
